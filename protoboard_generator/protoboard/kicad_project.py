"""The .kicad_pro and .kicad_dru.

The .kicad_pro carries the constraints that KiCad would otherwise take from its defaults, and the
.kicad_dru the fab's rules. Without them, DRC would check the board against the wrong limits.
"""

import json
import shutil
import sys
from pathlib import Path

from .constants import APPLY_WIRE_TRACK, FAB_RULES, MANUAL_LINE_WIDTH, PROJECT_CLEARANCE, PROJECT_RULES


def write_project(pcb_path, args, working=False):
    """Write <name>.kicad_pro and, if a fab was chosen, <name>.kicad_dru. A working copy also gets a wider
    default line on the other layers, so that the wires and chevrons drawn by hand on it stand out."""
    pcb_path = Path(pcb_path)
    pro_path = pcb_path.with_suffix(".kicad_pro")
    project = {
        "board": {
            "design_settings": {
                "rules": PROJECT_RULES,
                "rule_severities": {
                    # Footprints are generated by this script, not taken from a library.
                    "lib_footprint_issues": "ignore",
                    "lib_footprint_mismatch": "ignore",
                },
            },
        },
        "meta": {"filename": pro_path.name, "version": 1},
        "net_settings": {
            "classes": [{
                "name": "Default",
                "clearance": PROJECT_CLEARANCE,
                "track_width": args.track,
                "via_diameter": 0.6,
                "via_drill": 0.3,
                "diff_pair_gap": 0.25,
                "diff_pair_via_gap": 0.25,
                "diff_pair_width": 0.2,
                "microvia_diameter": 0.3,
                "microvia_drill": 0.1,
                "bus_width": 12,
                "wire_width": 6,
                "line_style": 0,
            }],
            "meta": {"version": 3},
        },
    }
    if working:
        project["board"]["design_settings"]["defaults"] = {"other_line_width": MANUAL_LINE_WIDTH}
        # The router draws the user's wires with the net class width: that of the applied wires, not of the strips.
        project["net_settings"]["classes"][0]["track_width"] = APPLY_WIRE_TRACK
    with open(pro_path, "w", encoding="utf-8") as fh:
        json.dump(project, fh, indent=2)
        fh.write("\n")
    written = [pro_path]

    if args.fab != "none":
        src = Path(__file__).resolve().parent.parent / "rules" / FAB_RULES[args.fab]
        if not src.exists():
            sys.exit(f"Cannot find {src}. Keep the 'rules' folder next to this script.")
        dru_path = pcb_path.with_suffix(".kicad_dru")
        shutil.copyfile(src, dru_path)
        written.append(dru_path)
    return written
